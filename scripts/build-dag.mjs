// Compiles src/dag/zachlef_in.py against the airflow stub with Pyodide (the
// same code the browser runs), and writes src/dag/generated.ts so the page can
// draw the default graph before Pyodide has loaded.

import { readFile, writeFile } from "node:fs/promises";
import { loadPyodide } from "pyodide";

const dir = new URL("../src/dag/", import.meta.url);
const stub = await readFile(new URL("airflow_stub.py", dir), "utf8");
const source = await readFile(new URL("zachlef_in.py", dir), "utf8");

const pyodide = await loadPyodide();
pyodide.runPython(stub);
const result = JSON.parse(pyodide.globals.get("compile_dag")(source));
if (!result.ok) {
  console.error(`zachlef_in.py line ${result.line}: ${result.error}`);
  process.exit(1);
}
const graph = { dagId: result.dagId, tasks: result.tasks, edges: result.edges };

await writeFile(
  new URL("generated.ts", dir),
  `// Generated by scripts/build-dag.mjs from airflow_stub.py and zachlef_in.py.
// Don't edit by hand: run \`pnpm dag\`.

import type { DagGraph } from "./types";

export const PYODIDE_VERSION = ${JSON.stringify(pyodide.version)};

export const AIRFLOW_STUB = ${JSON.stringify(stub)};

export const DEFAULT_DAG_SOURCE = ${JSON.stringify(source)};

export const DEFAULT_GRAPH: DagGraph = ${JSON.stringify(graph, null, 2)};
`,
);
console.log(
  `compiled ${graph.dagId}: ${graph.tasks.length} tasks, ${graph.edges.length} edges`,
);
